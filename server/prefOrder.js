// 「津営業所」より「津島営業所」を先に当てるため、長い都市名から順に試す
const KEYS_BY_LENGTH = Object.keys(PREF_OF_CITY).sort((a, b) => b.length - a.length);

/** 名前から都道府県番号（1〜47）。分からなければ99（末尾） */
export function prefRank(name) {
  const s = String(name ?? '').trim();
  for (const key of KEYS_BY_LENGTH) {
    if (s.startsWith(key)) return PREF_OF_CITY[key];
  }
  return 99;
}

/** 支店・営業所の並び比較。都道府県順 → 同じ県内は名前順 */
export function comparePref(a, b) {
  const ra = prefRank(a);
  const rb = prefRank(b);
  if (ra !== rb) return ra - rb;
  return String(a ?? '').localeCompare(String(b ?? ''), 'ja');
}
