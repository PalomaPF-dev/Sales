/**
 * 使い方のスライド。営業担当者が最初に見る前提で、
 * 「入力の仕方」「検索の仕方」「一覧の項目」を1枚ずつ見せる。
 * 文字だけで完結させ、画像は使わない（画面が変わっても古くならないように）。
 *
 * 画像を使わないぶん、<Where> で「どの画面のどこにあるか」を道順で必ず添える。
 * 「説明は分かったが、その欄がどこにあるのか分からない」を無くすため。
 */

/**
 * その操作をする場所への道順。
 * 例: <Where>左メニュー「案件一覧」→ 表を右へ →「入力」ボタン</Where>
 */
function Where({ children }: { children: React.ReactNode }) {
  return (
    <p className="help-where">
      <span className="pin">場所</span>
      <span className="path">{children}</span>
    </p>
  );
}

/** 一覧の項目説明で使う小さな表 */
function Terms({ rows }: { rows: [string, string][] }) {
  return (
    <table className="help-terms">
      <tbody>
        {rows.map(([k, v]) => (
          <tr key={k}>
            <th>{k}</th>
            <td>{v}</td>
          </tr>
        ))}
      </tbody>
    </table>
  );
}

